# Failed imports: actionable errors
# ---------------------------------------------------------------------------


def test_failed_import_shows_actionable_error(server_url: str, tmp_path: Path, page: Page) -> None:
    page.goto(f"{server_url}/imports")

    # A nonexistent path fails fast (400) -> inline notice, no background task.
    missing = tmp_path / "missing.zip"
    page.get_by_test_id("path-input").fill(str(missing))
    page.get_by_test_id("path-import-button").click()
    notice = page.get_by_test_id("start-error")
    expect(notice).to_be_visible()
    expect(notice).to_contain_text("no such file or directory")
    expect(page.get_by_test_id("task-failed")).to_have_count(0)

    # A corrupt archive passes the existence check, then fails during the
    # background detection phase — before any ledger row exists, so the
    # failure surfaces on the task card with the translated error.
    corrupt = tmp_path / "corrupt.zip"
    corrupt.write_bytes(b"PK\x03\x04" + b"\x00" * 64)
    page.get_by_test_id("path-input").fill(str(corrupt))
    page.get_by_test_id("path-import-button").click()
    failed = page.get_by_test_id("task-failed")
    expect(failed).to_be_visible(timeout=10_000)
    expect(failed).to_contain_text("corrupt.zip")
    expect(failed.get_by_test_id("task-error")).to_contain_text("corrupt or unreadable archive")

    # Actionable: the retry affordance refills the path input for a fix.
    page.get_by_test_id("path-input").fill("")
    failed.get_by_test_id("task-retry").click()
    expect(page.get_by_test_id("path-input")).to_have_value(str(corrupt))

    # And the notice is dismissable without losing the page.
    failed.get_by_role("button", name="Dismiss").click()
    expect(failed).to_have_count(0)


def test_failed_history_row_error_expands_and_retries(
    tmp_path: Path, page: Page, monkeypatch: pytest.MonkeyPatch
) -> None:
    # Seed a database with one completed run and one genuinely failed run —
    # through the real engine failure path (mid-parse exception marks the
    # ledger row failed with the error text, then re-raises).
    db_path = tmp_path / "potluck.db"
    settings = Settings(
        db_path=db_path,
        extract_attachments=False,
        attachments_dir=tmp_path / "attachments",
        uploads_dir=tmp_path / "uploads",
    )
    long_error = (
        "mbox member truncated at message 4: unexpected EOF while decoding a "
        "base64 attachment body — the archive appears incomplete; re-export "
        "this data from Google Takeout and import the fresh file instead"
    )
    broken_path = tmp_path / "broken-takeout-001.zip"

    def failing_drafts() -> Iterator[EmailDraft]:
        yield from synthetic_email_drafts(3, seed=SEED)
        raise RuntimeError(long_error)

    ctx = create_context(settings)
    try:
        import_path(ctx, write_keep_takeout(tmp_path / "keep", 5, seed=SEED, fmt="zip"))
        with pytest.raises(RuntimeError):
            run_import(
                ctx.db,
                source_name="gmail",
                parser_version=3,
                drafts=failing_drafts(),
                path=str(broken_path),
                file_hash=None,
            )
    finally:
        ctx.db.close()

    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    with serve_app(db_path, tmp_path / "config") as url:
        page.goto(f"{url}/imports")
        failed_row = page.locator('[data-testid="history-row"][data-status="failed"]')
        expect(failed_row).to_be_visible()
        expect(failed_row).to_have_attribute("data-source", "gmail")
        # Newest first: the failed gmail run precedes the completed keep run.
        expect(page.get_by_test_id("history-row").first).to_have_attribute("data-status", "failed")
        expect(page.get_by_test_id("history-row").nth(1)).to_have_attribute(
            "data-status", "completed"
        )

        # The error renders clamped, expands on demand, and offers a retry
        # that refills the path input with the failed archive's path.
        error = page.get_by_test_id("history-error")
        expect(error).to_contain_text("truncated at message 4")
        expect(error).to_have_attribute("data-expanded", "false")
        error.get_by_role("button", name="Show more").click()
        expect(error).to_have_attribute("data-expanded", "true")
        expect(error.get_by_role("button", name="Show less")).to_be_visible()
        error.get_by_test_id("history-retry").click()
        expect(page.get_by_test_id("path-input")).to_have_value(str(broken_path))


# ---------------------------------------------------------------------------
# Busy (409) and too-large (413) notices — intercepted envelopes
# ---------------------------------------------------------------------------


def test_busy_and_too_large_notices(server_url: str, tmp_path: Path, page: Page) -> None:
    page.goto(f"{server_url}/imports")

    # 409 import_in_progress -> a calm inline notice, not a crash.
    def busy_on_post(route: Route) -> None:
        if route.request.method == "POST":
            route.fulfill(status=409, content_type="application/json", body=BUSY_BODY)
        else:
            route.continue_()

    page.route("**/api/imports", busy_on_post)
    page.get_by_test_id("path-input").fill("/exports/other.zip")
    page.get_by_test_id("path-import-button").click()
    busy = page.get_by_test_id("start-busy")
    expect(busy).to_be_visible()
    expect(busy).to_contain_text("already running")
    page.unroute("**/api/imports")
    busy.get_by_role("button", name="Dismiss").click()
    expect(busy).to_have_count(0)

    # 413 upload_too_large -> a clear size message naming the limit.
    page.route(
        "**/api/imports/upload",
        lambda route: route.fulfill(
            status=413, content_type="application/json", body=TOO_LARGE_BODY
        ),
    )
    archive = write_keep_takeout(tmp_path / "fixture", 3, seed=SEED, fmt="zip")
    page.get_by_test_id("upload-input").set_input_files(archive)
    error = page.get_by_test_id("start-error")
    expect(error).to_be_visible()
    expect(error).to_contain_text("exceeds the configured limit")
