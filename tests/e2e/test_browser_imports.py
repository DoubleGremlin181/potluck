"""Browser tests for the SPA imports page (#136).

Drives the built SPA against a real ``potluck serve`` with synthetic archives
(generated by ``potluck.testing`` — never real exports): the upload flow, the
server-path flow over a two-part Takeout set, failed imports with actionable
errors, and the busy/too-large notices.

The concurrent-start (409) and oversized-upload (413) notices are exercised
via intercepted responses carrying the API's exact error envelope: gating a
real concurrent import on timing is flaky because synthetic fixtures import
in milliseconds.

Runs only with ``-m browser`` (excluded by default); requires ``web/dist``
and Playwright chromium.
"""

import shutil
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from playwright.sync_api import Page, Route, expect

from potluck.core.config import Settings
from potluck.ingest.engine import run_import
from potluck.models.drafts import EmailDraft
from potluck.services.context import create_context
from potluck.services.imports import import_path
from potluck.testing.keep import write_keep_takeout
from potluck.testing.mbox import synthetic_email_drafts, write_gmail_takeout
from tests.e2e.conftest import api_get, serve_app

pytestmark = pytest.mark.browser

SEED = 7

BUSY_BODY = (
    '{"error":{"code":"import_in_progress","message":'
    "\"an import of '/exports/big-takeout-001.zip' is already running; "
    'only one import runs at a time"}}'
)
TOO_LARGE_BODY = (
    '{"error":{"code":"upload_too_large","message":'
    "\"upload 'takeout-synth-001.zip' exceeds the configured limit of "
    '10737418240 bytes (settings: max_upload_bytes)"}}'
)


@pytest.fixture
def server_url(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[str]:
    """A fresh empty database per test; XDG_DATA_HOME pinned into tmp so the
    managed uploads directory never touches the developer's real data dir."""
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    with serve_app(tmp_path / "potluck.db", tmp_path / "config") as url:
        yield url


def api_imports(url: str) -> dict[str, Any]:
    """Ground-truth import history straight from the API."""
    return api_get(url, "/api/imports")


# ---------------------------------------------------------------------------
# Upload flow: fixture zip -> progress -> completed history row
# ---------------------------------------------------------------------------


def test_upload_zip_progress_then_history_row(server_url: str, tmp_path: Path, page: Page) -> None:
    archive = write_keep_takeout(tmp_path / "fixture", 12, seed=SEED, fmt="zip")

    page.goto(f"{server_url}/imports")
    expect(page.get_by_test_id("history-empty")).to_be_visible()

    page.get_by_test_id("upload-input").set_input_files(archive)

    # The 202 task snapshot seeds the UI the moment the POST resolves, so the
    # current-import card shows deterministically (for at least one poll
    # cycle) even though a 12-note import finishes server-side in ms.
    current = page.get_by_test_id("current-import")
    expect(current).to_be_visible()
    expect(current).to_contain_text("takeout-synth-001.zip")

    # The run lands in history as completed, with the same row shape as path
    # mode (the upload was stored under the managed uploads dir).
    row = page.get_by_test_id("history-row").first
    expect(row).to_have_attribute("data-status", "completed", timeout=15_000)
    expect(row).to_have_attribute("data-source", "google_keep")
    expect(row).to_contain_text("takeout-synth-001.zip")

    # Counts match the ledger row exactly (API = ground truth).
    truth = api_imports(server_url)["runs"][0]
    assert truth["items_done"] > 0
    expect(row.get_by_test_id("history-items")).to_contain_text(str(truth["items_done"]))
    expect(row.get_by_test_id("history-items")).to_contain_text(f"{truth['items_new']} new")

    # The operation settled: the current-import card goes away, polling stops.
    expect(current).to_have_count(0)


# ---------------------------------------------------------------------------
# Path mode: a TWO-PART Takeout set (Keep in part 1, Mail in part 2)
# ---------------------------------------------------------------------------


def test_path_mode_two_part_takeout_set(server_url: str, tmp_path: Path, page: Page) -> None:
    keep_zip = write_keep_takeout(tmp_path / "keep", 10, seed=SEED, fmt="zip")
    mail_zip = write_gmail_takeout(tmp_path / "mail", 15, seed=SEED, fmt="zip")
    set_dir = tmp_path / "takeout-set"
    set_dir.mkdir()
    part1 = set_dir / "takeout-e2e-001.zip"
    shutil.copy(keep_zip, part1)
    shutil.copy(mail_zip, set_dir / "takeout-e2e-002.zip")

    page.goto(f"{server_url}/imports")
    page.get_by_test_id("path-input").fill(str(part1))
    page.get_by_test_id("path-import-button").click()
    expect(page.get_by_test_id("current-import")).to_be_visible()

    # Pointing at ONE part imported the whole set: one operation, one ledger
    # row per detected source, both completed.
    rows = page.get_by_test_id("history-row")
    expect(rows).to_have_count(2, timeout=15_000)
    gmail_row = page.locator('[data-testid="history-row"][data-source="gmail"]')
    keep_row = page.locator('[data-testid="history-row"][data-source="google_keep"]')
    expect(gmail_row).to_have_attribute("data-status", "completed", timeout=15_000)
    expect(keep_row).to_have_attribute("data-status", "completed")
    # Both rows record the part the user pointed at.
    expect(gmail_row).to_contain_text("takeout-e2e-001.zip")
    expect(keep_row).to_contain_text("takeout-e2e-001.zip")

    truth = {run["source"]: run for run in api_imports(server_url)["runs"]}
    assert truth["gmail"]["items_done"] > 0 and truth["google_keep"]["items_done"] > 0
    expect(gmail_row.get_by_test_id("history-items")).to_contain_text(
        str(truth["gmail"]["items_done"])
    )
    expect(keep_row.get_by_test_id("history-items")).to_contain_text(
        str(truth["google_keep"]["items_done"])
    )


